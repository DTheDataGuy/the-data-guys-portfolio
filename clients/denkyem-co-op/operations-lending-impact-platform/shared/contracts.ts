// Denkyem dataset contract registry.
// Every dataset declares its grain, keys, source, owner and field contract.
// Forms, import mapping, validation, templates and the data dictionary are all generated from this file.

export type FieldType =
  | "id"
  | "text"
  | "longtext"
  | "date"
  | "month"
  | "money"
  | "int"
  | "decimal"
  | "percent"
  | "enum"
  | "zip"
  | "bool";

export interface FieldDef {
  key: string;
  label: string;
  type: FieldType;
  required?: boolean;
  aliases?: string[]; // legacy header names accepted at import (including misspellings)
  options?: string[];
  ref?: { dataset: string; field: string };
  restricted?: boolean; // personal / sensitive — never in aggregate or public output
  help?: string;
  min?: number;
}

export type Domain =
  | "impact"
  | "lending"
  | "crp"
  | "crsp"
  | "engagement"
  | "fundraising"
  | "finance"
  | "surveys"
  | "governance";

export interface DatasetDef {
  key: string;
  label: string;
  domain: Domain;
  kind: "dimension" | "fact" | "snapshot" | "reference";
  grain: string;
  uniqueKey: string[]; // business key within approved data
  snapshotKey?: string[]; // for snapshots: approval replaces/versions this slice
  dateField?: string;
  source: string;
  owner: string;
  cadence: string;
  legacyTable?: string;
  notes?: string;
  fields: FieldDef[];
}

