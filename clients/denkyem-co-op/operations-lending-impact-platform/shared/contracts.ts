export const LOAN_SIZE_BUCKETS = ["<10k", "10–25k", "25–50k", "50–100k", "100k+", "Unknown"] as const;
export function loanSizeBucket(amount: number | null | undefined): (typeof LOAN_SIZE_BUCKETS)[number] {
  if (amount === null || amount === undefined || Number.isNaN(amount)) return "Unknown";
  if (amount < 10000) return "<10k";
  if (amount < 25000) return "10–25k";
  if (amount < 50000) return "25–50k";
  if (amount < 100000) return "50–100k";
  return "100k+";
}
