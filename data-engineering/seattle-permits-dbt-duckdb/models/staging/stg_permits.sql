-- Staging: one row per permit, renamed and typed for the warehouse. No business logic here.
with source as (
    select * from {{ source('silver', 'permits') }}
)

select
    permit_num,
    permit_suffix,
    is_sub_permit,
    permit_class,
    permit_class_mapped,
    permit_type,
    coalesce(permit_type_desc, 'Unspecified')        as permit_work_class,
    status,
    description,
    housing_category,
    dwelling_unit_type,
    housing_units_net,
    coalesce(housing_units_added, 0)                 as housing_units_added,
    coalesce(housing_units_removed, 0)               as housing_units_removed,
    case when flag_cost_outlier then null else est_project_cost end as declared_value_usd,
    est_project_cost                                 as declared_value_raw_usd,
    applied_date,
    issued_date,
    expires_date,
    completed_date,
    days_to_issue,
    days_to_complete,
    plan_review_days,
    review_cycles,
    applied_month,
    applied_year,
    year(issued_date)                                as issued_year,
    address,
    city,
    zip,
    latitude,
    longitude,
    contractor,
    zoning,
    parent_permit_num,
    related_mup,
    is_dependent_building,
    flag_sentinel_date,
    flag_cost_outlier,
    flag_bad_geo,
    flag_bad_zip,
    source_url,
    _extract_id                                      as extract_id
from source
